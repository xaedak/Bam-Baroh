/** Given the freshest stats/save, returns achievement ids newly unlocked
 * (present in isMet() but not yet recorded in save.achievements). Because
 * `no_help_win` is set directly by the caller before this runs, it will be
 * picked up naturally on the same pass. */
export function findNewlyUnlocked(save: SaveData): Achievement[] {
  return ACHIEVEMENTS.filter((a) => save.achievements[a.id] === undefined && a.isMet(save.stats, save));
}

import { SaveData, StatsData } from '../types/game';

export type AchievementRarity = 'common' | 'rare' | 'epic' | 'legendary' | 'mythic';

export interface Achievement {
  id: string;
  title: string;
  description: string;
  icon: string;
  tokenReward: number;
  /** Display-only XP value shown on the unlock popup and achievements list. */
  xpReward: number;
  rarity: AchievementRarity;
  /** Returns true once the achievement's condition has been met. */
  isMet: (stats: StatsData, save: SaveData) => boolean;
  /** Returns a 0-1 progress value for display on locked achievements. */
  progress: (stats: StatsData, save: SaveData) => number;
}

function clamp01(n: number): number {
  if (Number.isNaN(n) || !Number.isFinite(n)) return 0;
  return Math.max(0, Math.min(1, n));
}

